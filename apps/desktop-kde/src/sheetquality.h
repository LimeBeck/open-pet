#pragma once

#include "corebridge.h"

#include <QStringList>

class QImage;

// Проверка качества спрайтового листа ([ADR-005](../../../docs/adr/0005-pet-pack-sprite-sheet.md)).
//
// Живёт в хосте, а не в ядре, намеренно. Разброс размера кадров считается
// по пикселям, а ядро изображения не декодирует — у него только разбор
// заголовка PNG. Тащить декодер в ядро ради подсказки о качестве
// несоразмерно: там граница безопасности, и каждая зависимость в ней
// оплачивается аудитом.
//
// Граница проходит так: ядро решает, можно ли пакет **принять**, хост
// говорит, хорошо ли он **нарисован**. Отказать в установке эти проверки
// не могут и не должны.
namespace SheetQuality {

// Предупреждения о заметном глазу дрожании фигуры между кадрами.
//
// Пустой список означает, что придраться не к чему, а не что проверка
// не выполнялась: непроверяемые случаи попадают в список отдельной строкой.
QStringList inspect(const QImage &sheet, const QList<CoreBridge::Animation> &animations,
                    const QStringList &names);

} // namespace SheetQuality
