#pragma once

// Автозапуск по явному выбору пользователя (§4.1).
//
// Реализован файлом `.desktop` в каталоге автозапуска XDG, а не своим
// механизмом: так пользователь может отключить автозапуск штатными
// средствами системы, не зная о существовании наших настроек.
//
// Приложение никогда не включает автозапуск само — «по явному выбору»
// означает, что галочку ставит человек.
class Autostart
{
public:
    static bool isEnabled();

    // Возвращает false, если файл не удалось создать или удалить: место
    // на диске, права, отсутствие каталога. Молчаливая неудача здесь хуже
    // всего — пользователь будет считать, что питомец запустится сам.
    static bool setEnabled(bool enabled);
};
