#pragma once

#include <QImage>
#include <QRegion>

namespace openpet {

// Параметры построения региона. Подобраны на спайке 01 и вынесены
// в параметры, а не оставлены константами: порог зависит от того,
// насколько мягкие края у конкретного питомца (ADR-002).
struct RegionOptions {
    // Огрубление сетки в логических пикселях. Режет число прямоугольников
    // в QRegion ценой точности по краю силуэта.
    int block = 4;
    // Граница, ниже которой пиксель считается прозрачным для попаданий.
    // Тень под питомцем не должна ловить клики.
    int alphaThreshold = 24;
};

// Строит input region по непрозрачным пикселям кадра.
//
// `scale` делит координаты результата: grabWindow() отдаёт изображение
// в физических пикселях, а маска окна задаётся в логических. Округление
// идёт наружу — лучше поймать лишний пиксель по краю, чем оставить дыру,
// в которую проваливается клик по питомцу.
QRegion regionFromAlpha(const QImage &image, const RegionOptions &options, qreal scale);

} // namespace openpet
