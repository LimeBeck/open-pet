#pragma once

#include <QImage>
#include <QRegion>

// Стратегии управления input region — варианты A…C из ADR-002.
// Вариант D (hit-test при полностью прозрачном для ввода окне) здесь не
// представлен: он проверяется отдельно, наблюдением, а не переключателем.
enum class RegionMode {
    // Регион не задаётся: окно ловит ввод целиком, включая прозрачные пиксели.
    // Базовая линия, показывающая масштаб проблемы.
    FullWindow = 0,
    // Вариант A: статический прямоугольник, заданный вручную вокруг питомца.
    StaticRect = 1,
    // Вариант B: регион по альфа-каналу, посчитанный один раз при старте.
    AlphaOnce = 2,
    // Вариант C: пересчёт региона на каждом кадре. Заведомо дорогой вариант,
    // нужен ради числа, а не ради использования.
    AlphaPerFrame = 3,
};

// Строит регион по непрозрачным пикселям изображения.
//
// `block` огрубляет сетку: регион собирается из блоков block×block, что режет
// число прямоугольников в QRegion ценой точности по краю силуэта. При block=1
// получается точный, но дорогой регион.
//
// `alphaThreshold` — граница, ниже которой пиксель считается прозрачным
// для попаданий. Полупрозрачная тень под питомцем не должна ловить клики.
//
// `scale` делит координаты результата: grabWindow() отдаёт изображение
// в физических пикселях, а маска окна задаётся в логических.
QRegion regionFromAlpha(const QImage &image, int block, int alphaThreshold, qreal scale);

const char *regionModeName(RegionMode mode);
